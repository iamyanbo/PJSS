"""Report of the one-at-a-time sensitivity sweep (benchmarks/sensitivity_bench.py) -> docs/reports/sensitivity.md.

    python benchmarks/sensitivity_report.py [--outdir results_sensitivity] [--output docs/reports/sensitivity.md]

Applies the rules of results_sensitivity/PREREGISTRATION.md exactly:
  * analysis set = sampled runs present in EVERY arm file (a common prefix of the random order if the sweep was cut);
    if it has fewer than 200 runs the report says the sweep is incomplete and states no verdict;
  * primary: exact-support rate per arm, difference to the default arm in percentage points, paired W/L
    (W = arm exact and default not), two-sided exact sign test on W vs L, Holm over the 18 perturbed arms;
  * error / timeout = not exact, F1 = 0, no coefficient error;
  * secondary: mean support F1; median relative coefficient error on runs exact in both the arm and the default;
  * claim rule: "robust" iff |exact(arm) - exact(default)| <= 5.0 points for all 18 arms.
Can be run at any time (also on partial results); it only reads.
"""
import argparse
import json
from math import comb
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[1]
ORDER = ["degw", "centre", "arthr", "penexp", "huber", "rho", "kmax", "finalists", "sgwin"]
LABEL = {"degw": "complexity prior strength degw (0.2)", "centre": "prior centre c (1.5)",
         "arthr": "AR(1) switch threshold (0.6)", "penexp": "AR(1) penalty exponent pen_exp (1/3)",
         "huber": "Huber constant, white path (2)", "rho": "model-error scale rho (0.03)",
         "kmax": "max terms per equation in proposals kmax (5)", "finalists": "proposals refitted per round (10)",
         "sgwin": "Savitzky-Golay window of initial states (21)"}
MARGIN, MIN_RUNS = 5.0, 200


def sign_p(w, l):
    n = w + l
    if n == 0:
        return 1.0
    k = min(w, l)
    return min(1.0, 2 * sum(comb(n, i) for i in range(k + 1)) / 2 ** n)


def holm(ps):
    order = np.argsort(ps)
    adj, run = np.empty(len(ps)), 0.0
    for r, i in enumerate(order):
        run = max(run, min(1.0, (len(ps) - r) * ps[i]))
        adj[i] = run
    return adj


def f1(r):
    return r["metrics"].get("f1", 0.0) if r["status"] == "ok" else 0.0


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--outdir", default="results_sensitivity")
    ap.add_argument("--output", default="docs/reports/sensitivity.md")
    a = ap.parse_args()
    od = REPO / a.outdir
    smp = json.loads((od / "sample.json").read_text())
    A = {p.stem: json.loads(p.read_text()) for p in sorted((od / "arms").glob("*.json"))}
    if "default" not in A:
        raise SystemExit("no default arm yet")
    arms = [k for g in ORDER for k in sorted(A) if k.startswith(g + "_")]
    keys = [str(m["index"]) for m in smp["runs"] if all(str(m["index"]) in A[k]["records"] for k in A)]
    n = len(keys)
    dflt = A["default"]["records"]
    e0 = np.array([dflt[k]["metrics"]["exact"] for k in keys])
    rows = []
    for arm in arms:
        R = A[arm]["records"]
        e1 = np.array([R[k]["metrics"]["exact"] for k in keys])
        w, l = int(((e1 == 1) & (e0 == 0)).sum()), int(((e1 == 0) & (e0 == 1)).sum())
        both = [k for k in keys if R[k]["metrics"]["exact"] == 1 and dflt[k]["metrics"]["exact"] == 1]
        ce = np.median([R[k]["metrics"]["coef_err"] for k in both]) if both else np.nan
        ce0 = np.median([dflt[k]["metrics"]["coef_err"] for k in both]) if both else np.nan
        rows.append(dict(arm=arm, kw=A[arm]["kwargs"], exact=e1.mean() if n else np.nan,
                         diff=100 * (e1.mean() - e0.mean()) if n else np.nan, w=w, l=l, p=sign_p(w, l),
                         f1=np.mean([f1(R[k]) for k in keys]) if n else np.nan, ce=ce, ce0=ce0,
                         err=sum(R[k]["status"] != "ok" for k in keys),
                         copied=sum(bool(R[k].get("copied_from_default")) for k in keys),
                         beam=sum(bool(R[k].get("beam_search")) for k in keys),
                         secs=sum(R[k]["seconds"] for k in keys), cc=A[arm].get("copy_check")))
    if rows:
        for r, q in zip(rows, holm(np.array([r["p"] for r in rows]))):
            r["holm"] = q
    complete = n >= MIN_RUNS and len(arms) == 18
    out = ["# Sensitivity of the fixed constants (one at a time, x0.5 / x2)", "",
           "Generated by `benchmarks/sensitivity_report.py` from `results_sensitivity/` (sweep: "
           "`benchmarks/sensitivity_bench.py`). Rules fixed in advance in `results_sensitivity/PREREGISTRATION.md`.",
           "", f"Analysis set: {n} of {len(smp['runs'])} sampled runs (dysts, the 49 systems never used in "
           f"development; stratified over system x noise level, seed {smp['seed']}), present in all "
           f"{len(A)} arm files. Default arm (v1.2): exact {e0.mean():.3f} ({int(e0.sum())}/{n}), "
           f"mean F1 {np.mean([f1(dflt[k]) for k in keys]):.3f}, errors/timeouts "
           f"{sum(dflt[k]['status'] != 'ok' for k in keys)}.", ""]
    if not complete:
        out += [f"**Incomplete sweep** ({n} common runs, {len(arms)} perturbed arms; the pre-registered verdict "
                f"needs >= {MIN_RUNS} runs in all 18 arms). Numbers below are interim.", ""]
    out += ["| constant | arm | value | exact | diff (pts) | W/L | sign p | Holm p | mean F1 | median coef err "
            "(both exact: arm / default) | errors | copied |",
            "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        g = r["arm"].split("_")[0]
        out.append(f"| {LABEL[g]} | {r['arm']} | {', '.join(f'{k}={v:.4g}' for k, v in r['kw'].items())} | "
                   f"{r['exact']:.3f} | {r['diff']:+.1f} | {r['w']}/{r['l']} | {r['p']:.3g} | {r['holm']:.3g} | "
                   f"{r['f1']:.3f} | {r['ce']:.2e} / {r['ce0']:.2e} | {r['err']} | {r['copied']} |")
    out.append("")
    outside = [r for r in rows if abs(r["diff"]) > MARGIN]
    if complete:
        if not outside:
            out += [f"**Verdict (pre-registered rule): robust.** All 18 arms are within {MARGIN:.0f} points of the "
                    f"default (largest |diff| {max(abs(r['diff']) for r in rows):.1f} points, "
                    f"{max(rows, key=lambda r: abs(r['diff']))['arm']})."]
        else:
            out += [f"**Verdict (pre-registered rule): not robust.** {len(outside)} arm(s) outside "
                    f"+-{MARGIN:.0f} points: " + ", ".join(f"{r['arm']} ({r['diff']:+.1f})" for r in outside) + "."]
        sig = [r for r in rows if r["holm"] < 0.05]
        out += ["", "Paired sign tests significant after Holm (0.05): "
                + (", ".join(f"{r['arm']} ({r['w']}/{r['l']}, Holm p {r['holm']:.2g})" for r in sig) or "none") + "."]
    # per-constant summary and subgroup view
    out += ["", "## By subgroup (exact rate; default vs worst arm of each constant)", "",
            "| subgroup | runs | default | " + " | ".join(ORDER) + " |", "|---|---|---|" + "---|" * len(ORDER)]
    meta = {str(m["index"]): m for m in smp["runs"]}
    groups = [("D = 3", lambda m: m["D"] == 3), ("D >= 4 (joint_nd)", lambda m: m["D"] >= 4),
              ("n = 500", lambda m: m["n"] == 500), ("n = 2000", lambda m: m["n"] == 2000)] + \
             [(f"noise {s}", (lambda s: lambda m: m["noise"] == s)(s)) for s in sorted({m["noise"] for m in meta.values()})]
    for lab, fn in groups:
        ks = [k for k in keys if fn(meta[k])]
        if not ks:
            continue
        d0 = np.mean([dflt[k]["metrics"]["exact"] for k in ks])
        cells = []
        for g in ORDER:
            vals = [(np.mean([A[r["arm"]]["records"][k]["metrics"]["exact"] for k in ks]), r["arm"])
                    for r in rows if r["arm"].startswith(g + "_")]
            cells.append(f"{min(vals)[0]:.3f}" if vals else "-")
        out.append(f"| {lab} | {len(ks)} | {d0:.3f} | " + " | ".join(cells) + " |")
    nm = [dflt[k].get("noise_model") for k in keys]
    out += ["", "## Notes", "",
            f"* Default routing: {nm.count('ar1')} of {n} runs to the AR(1) model, {nm.count('white')} white "
            f"(D >= 4 runs are always white, joint_nd). The AR(1)-threshold and pen_exp arms can only act on runs "
            "near / above the switch, so on this white-noise archive they test little.",
            "* Copied records (constant provably inactive on that run; see sensitivity_bench docstring) and their "
            "recomputation checks: " + "; ".join(f"{r['arm']}: {r['copied']} copied, check "
                                                 f"{(r['cc'] or {}).get('verified', 0)} identical"
                                                 f"{' FAILED' if (r['cc'] or {}).get('failed') else ''}"
                                                 for r in rows if r["arm"].startswith(("arthr", "penexp"))) + ".",
            f"* kmax_x2 (kmax = 10) on D = 3 uses beam-search proposals (joint_biglib, width 60) in {sum(r['beam'] for r in rows)} "
            "run(s): the exhaustive subset search refuses kmax > 7 on the 20-term library.",
            "* Compute (one core): " + ", ".join(f"{r['arm']} {r['secs'] / 3600:.1f} h" for r in rows)
            + f", default {sum(dflt[k]['seconds'] for k in keys) / 3600:.1f} h."]
    p = REPO / a.output
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
